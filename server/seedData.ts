function buildStock(
  sizes: string[],
  colors: ProductColor[],
  baseQty: number,
  zeroFirstCombo = false,
): Record<string, Record<string, number>> {
  const matrix: Record<string, Record<string, number>> = {};
  sizes.forEach((size, si) => {
    matrix[size] = {};
    colors.forEach((c, ci) => {
      if (zeroFirstCombo && si === sizes.length - 1 && ci === colors.length - 1) {
        matrix[size][c.name] = 0;
      } else {
        matrix[size][c.name] = Math.max(2, baseQty + ((si * 2 + ci) % 5));
      }
    });
  });
  return matrix;
}

function makeProduct(
  idx: number,
  data: Omit<Product, 'id' | 'sku' | 'stockByVariant' | 'createdAt' | 'careInstructions' | 'reviewCount'> & {
    baseStock?: number;
    zeroLastVariant?: boolean;
    customStock?: Record<string, Record<string, number>>;
  },
): Product {
  const num = String(idx).padStart(3, '0');
  const day = String(Math.max(1, 28 - (idx % 25))).padStart(2, '0');
  return {
    id: `prod-${num}`,
    sku: `US-26-${num}`,
    careInstructions: 'Lavar a mano o ciclo delicado en agua fría (30 °C). Secar a la sombra. No usar blanqueador.',
    reviewCount: 4 + (idx % 14),
    createdAt: `2026-10-${day}T10:00:00.000Z`,
    ...data,
    stockByVariant:
      data.customStock ||
      buildStock(data.sizes, data.colors, data.baseStock ?? 5, Boolean(data.zeroLastVariant)),
  };
}

